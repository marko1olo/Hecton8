    /// <summary>
    /// Branch-light selector for immutable baked mesh hashes. No UnityEngine object reference crosses this contract.
    /// Pressure reaches all baked states; visual buckling scalar stays continuous between thresholds.
    /// </summary>
    public static class HabitatDamageMeshStateResolver
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static byte ResolveStateIndex(float pressure01)
        {
            float p = math.saturate(math.isfinite(pressure01) ? pressure01 : 0f);
            float stressed = math.step(0.33333334f, p);
            float ruptured = math.step(0.6666667f, p);
            float collapsed = math.step(0.95f, p);
            return (byte)(stressed + ruptured + collapsed);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static float ResolveVisualBuckling01(float pressure01)
        {
            float p = math.saturate(math.isfinite(pressure01) ? pressure01 : 0f);
            return math.smoothstep(0.33333334f, 0.95f, p);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static uint ResolveMeshHash(in ModuleDamageStateMappingDTO mapping, byte stateIndex)
        {
            int state = math.clamp((int)stateIndex, 0, 3);
            uint hash = mapping.PristineMeshHash;
            hash = math.select(hash, mapping.StressedMeshHash, state >= 1);
            hash = math.select(hash, mapping.RupturedMeshHash, state >= 2);
            hash = math.select(hash, mapping.CollapsedMeshHash, state >= 3);
            return hash;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static uint ResolveMeshHash(in ModuleDamageStateMappingDTO mapping, float pressure01)
        {
            return ResolveMeshHash(in mapping, ResolveStateIndex(pressure01));
        }
    }
