    /// <summary>
    /// Stable baked mesh state selected by structural pressure truth.
    /// </summary>
    public enum HabitatDamageMeshState : byte
    {
        Intact = 0,
        Stressed = 1,
        Ruptured = 2,
        Collapsed = 3
    }

    /// <summary>
