        /// <summary>
        /// Union of both manifest shapes the forge writes today. Tier 1 is
        /// <c>h8forge.export_unity.write_manifest</c> (<c>schema</c>, <c>unityImport</c>, <c>export</c>,
        /// <c>lod</c>). Tier 2 is the generator-local shape <c>generators/kelp.py</c> and
        /// <c>generators/rock.py</c> actually emit (<c>identity</c>, <c>files</c>, <c>lods</c>,
        /// <c>materialSlots</c>, <c>validation.allPassed</c>) because neither generator has been migrated onto
        /// the shared exporter yet. The two shapes share no field name, so one reader covers both.
        /// </summary>
        [Serializable]
        private sealed class ForgeManifestFile
        {
            public string schema;
            public ForgeManifestUnityImportBlock unityImport;
            public ForgeManifestExportBlock export;
            public ForgeManifestLodBlock lod;
            public ForgeManifestIdentityBlock identity;
            public ForgeManifestFilesBlock files;
            public ForgeManifestLodEntry[] lods;
            public ForgeManifestMaterialSlotEntry[] materialSlots;
            public ForgeManifestValidationBlock validation;
            public ForgeManifestVatReadinessBlock vatReadiness;
            public ForgeManifestExtraBlock extra;
        }

        /// <summary>
        /// The forge's <c>extra</c> payload. This is where <c>vatReadiness</c> ACTUALLY lands:
        /// <c>export_unity.write_manifest</c> takes a first-class <c>extra</c> keyword (export_unity.py:1908)
        /// and assigns it wholesale (<c>payload["extra"] = extra</c>, :2134-2135), and every family-specific
        /// block goes through it - fauna_fish.py:2214, prop_handtool.py:1682, flora_capstem.py:2611. The
        /// exporter's payload dict offers no root slot for generator blocks at all, so <c>extra</c> is the
        /// sanctioned home and the C# reader was the wrong side of this disagreement.
        /// Only <c>vatReadiness</c> is typed here; JsonUtility drops <c>extra</c>'s heterogeneous siblings
        /// (<c>bodyPlan</c>, <c>consumerContract</c>, strings, arrays) because no field claims them, which is
        /// why this needs no <c>Dictionary</c> - which JsonUtility would not support anyway.
        /// </summary>
        [Serializable]
        private sealed class ForgeManifestExtraBlock
        {
            public ForgeManifestVatReadinessBlock vatReadiness;
        }

        /// <summary>
        /// The <c>vatReadiness</c> block. Its PRESENCE is what identifies a Vertex Animation Texture
        /// source; it is written only by generators whose family animates through a baked VAT. Read it
        /// through <see cref="ResolveVatReadiness"/> rather than off a field directly - the forge nests it
        /// under <c>extra</c>, and only that helper accepts both placements.
        /// </summary>
        /// <remarks>
        /// The carve-out is deliberately NOT keyed on
        /// <c>unityImport.modelImporter.isReadable</c>: the fish manifest declares that field <c>false</c>,
        /// because the forge is describing the shipped runtime state of the asset rather than what an offline
        /// bake needs from it. Honouring that field literally would keep the mesh unreadable and leave the
        /// chain exactly as blocked as before, so the signal has to be "this is a VAT source" rather than
        /// "this asset asked to be readable". Only <c>vertexCountLOD0</c> is deserialised; the block's other
        /// keys are informational and JsonUtility drops what it has no field for.
        /// </remarks>
        [Serializable]
        private sealed class ForgeManifestVatReadinessBlock
        {
            public int vertexCountLOD0;
        }

        /// <summary>
        /// Reads the <c>vatReadiness</c> block from whichever placement the manifest uses.
        /// </summary>
        /// <remarks>
        /// The forge nests it under <c>extra</c> (export_unity.py:2134-2135, fauna_fish.py:2239) while this
        /// reader originally expected it at the root, so <c>IsVatSource</c> was always false and
        /// <c>ReimportVatSourceModel</c> exited 3 - JsonUtility leaves an unmatched field at its default
        /// rather than throwing, so the disagreement was silent rather than diagnosable. Root is preferred so
        /// any manifest already written that way keeps working; <c>extra</c> is the sanctioned home going
        /// forward and is what every current generator emits.
        /// </remarks>
        private static ForgeManifestVatReadinessBlock ResolveVatReadiness(ForgeManifestFile manifest)
        {
            if (manifest == null)
                return null;

            if (manifest.vatReadiness != null)
                return manifest.vatReadiness;

            return manifest.extra != null ? manifest.extra.vatReadiness : null;
        }

        /// <summary>
        /// Maps a managed FBX asset path to the path its sibling forge manifest must occupy, or returns false.
        /// Pure string logic with no file access, so the naming gate is provable without an import.
        /// </summary>
        internal static bool TryResolveForgeManifestPath(string assetPath, out string manifestPath)
        {
            manifestPath = string.Empty;
            if (string.IsNullOrEmpty(assetPath))
                return false;

            string normalizedPath = assetPath.Replace('\\', '/');
            if (!normalizedPath.EndsWith(ForgeFbxExtension, StringComparison.OrdinalIgnoreCase))
                return false;

            // Third-party quarantine can never earn the carve-out. ImporterMatchesScifiFacilityPolicy asserts
            // the strict vendor policy for this root, and a manifest dropped beside a vendor FBX must not be
            // able to weaken it.
            if (IsUnderRoot(normalizedPath, ScifiFacilityRoot))
                return false;

            int lastSlash = normalizedPath.LastIndexOf('/');
            string directory = lastSlash >= 0 ? normalizedPath.Substring(0, lastSlash + 1) : string.Empty;
            string fileName = normalizedPath.Substring(lastSlash + 1);

            // Ordinal and case-sensitive, and the trailing underscore is what carries the gate: law.NAME_MESH
            // writes upper-case "MESH_", so the existing
            // Assets/_Project/Art/Materials/Meshy_AI_Alien_barnacles_clust_0301230506_texture.fbx does not
            // match, and neither does any lower-case variant.
            if (!fileName.StartsWith(ForgeMeshFilePrefix, StringComparison.Ordinal))
                return false;

            int stemLength = fileName.Length - ForgeMeshFilePrefix.Length - ForgeFbxExtension.Length;
            if (stemLength <= 0)
                return false;

            string stem = fileName.Substring(ForgeMeshFilePrefix.Length, stemLength);
            manifestPath = directory + ForgeManifestFilePrefix + stem + ForgeManifestExtension;
            return true;
        }

        /// <summary>
        /// Reads one forge manifest body and derives the carve-out. Pure apart from its error logging, so the
        /// accept/reject decision is provable from a JSON string with no FBX and no import.
        /// </summary>
        internal static bool TryParseForgeImportContract(
            string manifestJson,
            string manifestPath,
            string fbxFileName,
            out ForgeImportContract contract)
        {
            contract = default;
            if (string.IsNullOrEmpty(manifestJson))
                return false;

            ForgeManifestFile manifest;
            try
            {
                manifest = JsonUtility.FromJson<ForgeManifestFile>(manifestJson);
            }
            catch (Exception error)
            {
                // Deliberately broad and deliberately loud. An unhandled exception here aborts the import of a
                // real asset, which is strictly worse than falling back to the unchanged project policy. The
                // failure is never swallowed: without this line a malformed manifest would be indistinguishable
                // from an asset that simply has no manifest.
                Debug.LogError(
                    "[HectonFBXPostprocessor] Forge manifest '" + manifestPath + "' could not be parsed, so " +
                    "the offline import contract is NOT honoured and the strict project policy applies: " +
                    error.GetType().Name + ": " + error.Message);
                return false;
            }

            if (manifest == null)
                return false;

            // -- tier 1: the manifest states the importer contract itself ------------------------------------
            if (string.Equals(manifest.schema, ForgeManifestSchema, StringComparison.Ordinal))
            {
                ForgeManifestModelImporterBlock declared =
                    manifest.unityImport != null ? manifest.unityImport.modelImporter : null;
                if (declared == null)
                {
                    Debug.LogError(
                        "[HectonFBXPostprocessor] Forge manifest '" + manifestPath + "' declares schema '" +
                        ForgeManifestSchema + "' but carries no unityImport.modelImporter block, so there is " +
                        "no import contract to honour and the strict project policy applies.");
                    return false;
                }

                // 3dmodel.md section 3 gives normals to the generator, but only a package that actually wrote
                // custom split normals has anything for Unity to import. Without them, Import would hand the
                // shader whatever the file happens to hold and Calculate is the honest strategy.
                bool authoredNormals =
                    string.Equals(declared.importNormals, ForgeImportNormalsImportToken, StringComparison.Ordinal) &&
                    manifest.export != null &&
                    manifest.export.hasCustomNormals;

                contract = new ForgeImportContract(
                    manifestPath,
                    true,
                    authoredNormals,
                    SanitizeNormalSmoothingAngle(declared.normalSmoothingAngle),
                    !declared.generateSecondaryUV,
                    string.Equals(declared.materialImportMode, ForgeMaterialImportModeNoneToken, StringComparison.Ordinal),
                    manifest.lod != null && manifest.lod.levels != null ? manifest.lod.levels.Length : 0,
                    // A positive authored LOD0 vertex count is the presence test. The block exists only on
                    // packages whose family renders through a baked VAT, and requiring a real count rather than
                    // mere non-nullness keeps an empty or default-constructed block from granting anything.
                    // ResolveVatReadiness checks both the root field (old manifests) and extra.vatReadiness
                    // (current forge output) so neither placement is silently missed.
                    ResolveVatReadiness(manifest) != null && ResolveVatReadiness(manifest).vertexCountLOD0 > 0);
                return true;
            }

            // -- tier 2: generator-local manifest, provenance only -------------------------------------------
            // No importer contract is declared here, so nothing is assumed field by field. Provenance must be
            // proven three independent ways before any relaxation applies.
            if (manifest.identity == null ||
                string.IsNullOrEmpty(manifest.identity.generator) ||
                string.IsNullOrEmpty(manifest.identity.forgeVersion))
            {
                return false;
            }

            // The manifest has to name the exact file sitting beside it. rock.py records a full path and
            // kelp.py a bare name, so the comparison is on the file name only.
            if (manifest.files == null || string.IsNullOrEmpty(manifest.files.fbx))
                return false;

            string declaredFbx = manifest.files.fbx.Replace('\\', '/');
            int declaredSlash = declaredFbx.LastIndexOf('/');
            if (declaredSlash >= 0)
                declaredFbx = declaredFbx.Substring(declaredSlash + 1);
            if (!string.Equals(declaredFbx, fbxFileName, StringComparison.OrdinalIgnoreCase))
                return false;

            // A package whose own gates failed does not get relaxed treatment. 3dmodel.md section 10: "Failure
            // aborts save."
            if (manifest.validation == null || !manifest.validation.allPassed)
                return false;

            int authoredLods = 0;
            if (manifest.lods != null)
            {
                for (int i = 0; i < manifest.lods.Length; i++)
                {
                    if (manifest.lods[i] != null && manifest.lods[i].lod >= 0)
                        authoredLods++;
                }
            }

            // Shared materials only when every declared slot names a MAT_* asset. One empty slot means the
            // package has not resolved its material contract and Unity's own import is no worse.
            bool ownsSharedMaterials = false;
            if (manifest.materialSlots != null)
            {
                for (int i = 0; i < manifest.materialSlots.Length; i++)
                {
                    if (manifest.materialSlots[i] == null ||
                        string.IsNullOrEmpty(manifest.materialSlots[i].material))
                    {
                        ownsSharedMaterials = false;
                        break;
                    }

                    ownsSharedMaterials = true;
                }
            }

            // Normals: provenance plus 3dmodel.md section 3, "A generator owns normals, tangents, UVs, and
            // bounds because it owns the geometry."
            // Secondary UV is deliberately NOT suppressed on this tier. A generator-local manifest records no
            // UV1 layer at all, so forcing Unity's generator off could leave the asset with no TexCoord1
            // whatsoever, and section 3 requires TexCoord1 only "when required".
            // normalSmoothingAngle is left at 0, meaning undeclared: the importer's angle is not touched.
            contract = new ForgeImportContract(
                manifestPath,
                false,
                true,
                ForgeMinNormalSmoothingAngle,
                false,
                ownsSharedMaterials,
                authoredLods,
                // Never a VAT source on this tier. See ForgeImportContract.IsVatSource: tier 2 proves
                // provenance only, so a readability or vertex-identity relaxation from it would be assumed.
                false);
            return true;
        }

        private static float SanitizeNormalSmoothingAngle(float declaredAngle)
        {
            // 0 means "the manifest declared none"; anything outside the legal dihedral range is treated the
            // same way rather than being written onto the importer.
            if (declaredAngle <= ForgeMinNormalSmoothingAngle || declaredAngle > ForgeMaxNormalSmoothingAngle)
                return ForgeMinNormalSmoothingAngle;

            return declaredAngle;
        }

        /// <summary>
        /// Resolves the offline forge import contract for one managed FBX, or returns false for every other
        /// asset. The manifest is re-read on every call: an import-time cache would go stale inside a session
        /// and silently apply a previous manifest's relaxations, which is the exact silent-wrong-output failure
        /// this carve-out exists to prevent.
        /// </summary>
        /// <remarks>
        /// The manifest is read with plain file IO, so it is NOT registered as an import dependency: editing a
        /// manifest does not retrigger the FBX import on its own. Use the
        /// "Hecton8/Validation/Asset Pipeline/Reimport FBX - ..." menu items after changing one.
        /// </remarks>
        internal static bool TryResolveForgeImportContract(string assetPath, out ForgeImportContract contract)
        {
            contract = default;
            if (!TryResolveForgeManifestPath(assetPath, out string manifestPath))
                return false;

            string absoluteManifestPath = ResolveProjectAbsolutePath(manifestPath);
            if (!System.IO.File.Exists(absoluteManifestPath))
                return false;

            string manifestJson;
            try
            {
                manifestJson = System.IO.File.ReadAllText(absoluteManifestPath);
            }
            catch (System.IO.IOException error)
            {
                Debug.LogError(
                    "[HectonFBXPostprocessor] Forge manifest '" + manifestPath + "' exists but could not be " +
                    "read, so the strict project policy applies to '" + assetPath + "': " + error.Message);
                return false;
            }
            catch (UnauthorizedAccessException error)
            {
                Debug.LogError(
                    "[HectonFBXPostprocessor] Forge manifest '" + manifestPath + "' is not readable, so the " +
                    "strict project policy applies to '" + assetPath + "': " + error.Message);
                return false;
            }

            string normalizedPath = assetPath.Replace('\\', '/');
            string fbxFileName = normalizedPath.Substring(normalizedPath.LastIndexOf('/') + 1);
            return TryParseForgeImportContract(manifestJson, manifestPath, fbxFileName, out contract);
        }

        private static string ResolveProjectAbsolutePath(string projectRelativePath)
        {
            // AGENTS.md Relative Path Requirement: resolve from the project root through Application.dataPath
            // rather than the process working directory, which an out-of-process asset import worker does not
            // guarantee, and never from a hardcoded developer path.
            string assetsFolder = Application.dataPath.Replace('\\', '/');
            int lastSlash = assetsFolder.LastIndexOf('/');
            string projectRoot = lastSlash > 0 ? assetsFolder.Substring(0, lastSlash) : assetsFolder;
            return projectRoot + "/" + projectRelativePath;
        }

        private static void LogForgeCarveOut(string assetPath, in ForgeImportContract contract)
        {
            // Loud on purpose, and a warning rather than a log: this is the one place the project's default
            // model-import policy is relaxed, and a plain Debug.Log is lost in Unity's import chatter. The
            // deviation must never be invisible, which is the same reason the auto-LOD fallback warns.
            Debug.LogWarning(
                "[HectonFBXPostprocessor] FORGE IMPORT CARVE-OUT applied to '" + assetPath + "' on the " +
                "authority of manifest '" + contract.ManifestPath + "' (" +
                (contract.DeclaredImportContract
                    ? "schema " + ForgeManifestSchema + ", explicit unityImport.modelImporter contract"
                    : "generator-local manifest; provenance proven by identity.generator, identity.forgeVersion, files.fbx and validation.allPassed") +
                "). importNormals=Import: " + contract.ImportAuthoredNormals +
                "; normalSmoothingAngle declared: " +
                contract.NormalSmoothingAngle.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture) +
                "; generateSecondaryUV forced off: " + contract.SuppressSecondaryUv +
                "; materialImportMode=None: " + contract.SuppressMaterialImport +
                "; authored LOD levels: " + contract.AuthoredLodLevelCount +
                (contract.IsVatSource
                    ? "; VAT SOURCE: isReadable=true, weldVertices=false, meshOptimizationFlags=PolygonOrder. " +
                      "These three keep per-vertex identity stable so a baked VAT stays synchronised with the " +
                      "mesh it indexes. Changing any of them later invalidates every VAT baked from this asset " +
                      "and requires a re-bake."
                    : "; not a VAT source: isReadable stays false and vertex identity is left at Unity defaults") +
                ". Every FBX without a matching sibling forge manifest keeps the unchanged project policy.");
        }

        private static bool IsUnderRoot(string path, string root)
        {
            if (string.IsNullOrEmpty(path) || string.IsNullOrEmpty(root))
                return false;

            string normalizedPath = path.Replace('\\', '/');
            string normalizedRoot = root.Replace('\\', '/');
            return normalizedPath.StartsWith(normalizedRoot, StringComparison.OrdinalIgnoreCase);
        }
