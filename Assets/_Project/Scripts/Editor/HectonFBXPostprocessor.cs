        [MenuItem("Hecton8/Validation/Asset Pipeline/Validate FBX - ScifiFacility", priority = 183)]
        private static void ValidateScifiFacilityFbxPolicy()
        {
            List<string> fbxPaths = CollectFbxPaths(new[] { ScifiFacilityRoot });
            int mismatchCount = 0;

            for (int i = 0; i < fbxPaths.Count; i++)
            {
                ModelImporter importer = AssetImporter.GetAtPath(fbxPaths[i]) as ModelImporter;
                if (!ImporterMatchesScifiFacilityPolicy(importer))
                {
                    mismatchCount++;
                    Debug.LogError($"[HectonFBXPostprocessor] ScifiFacility importer policy drift: '{fbxPaths[i]}'.");
                }
            }

            if (mismatchCount <= 0)
            {
                Debug.Log($"[HectonFBXPostprocessor] Validated {fbxPaths.Count} ScifiFacility FBX assets. No importer drift detected.");
                return;
            }

            Debug.LogError($"[HectonFBXPostprocessor] Found {mismatchCount} ScifiFacility FBX assets with importer drift.");
        }

        internal static List<string> CollectFbxPaths(string[] searchRoots)
        {
            string[] modelGuids = AssetDatabase.FindAssets("t:Model", searchRoots);
            List<string> paths = new List<string>(modelGuids.Length);
            HashSet<string> uniquePaths = new HashSet<string>(modelGuids.Length, StringComparer.Ordinal);

            for (int i = 0; i < modelGuids.Length; i++)
            {
                string assetPath = AssetDatabase.GUIDToAssetPath(modelGuids[i]);
                if (!IsManagedModelAsset(assetPath) || !uniquePaths.Add(assetPath))
                    continue;

                paths.Add(assetPath);
            }

            paths.Sort(StringComparer.Ordinal);
            return paths;
        }

        internal static List<string> ReimportFbxAssets(string[] searchRoots)
        {
            List<string> fbxPaths = CollectFbxPaths(searchRoots);

            try
            {
                for (int i = 0; i < fbxPaths.Count; i++)
                {
                    string assetPath = fbxPaths[i];
                    EditorUtility.DisplayProgressBar(
                        "HECTON-8 Model Reimport",
                        assetPath,
                        fbxPaths.Count > 0 ? (i + 1f) / fbxPaths.Count : 1f);
                    AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceUpdate);
                }
            }
            finally
            {
                EditorUtility.ClearProgressBar();
            }

            return fbxPaths;
        }

        private void OnPreprocessModel()
        {
            ModelImporter importer = assetImporter as ModelImporter;
            if (importer == null || !IsManagedModelAsset(assetPath))
                return;

            ApplyImporterPolicy(importer);
        }

        private void OnPostprocessModel(GameObject importedRoot)
        {
            if (importedRoot == null || !IsManagedModelAsset(assetPath))
                return;

            NormalizeImportedRootName(importedRoot);

            MeshFilter[] meshFilters = importedRoot.GetComponentsInChildren<MeshFilter>(true);
            int totalTriangles = 0;
            for (int i = 0; i < meshFilters.Length; i++)
            {
                Mesh mesh = meshFilters[i] != null ? meshFilters[i].sharedMesh : null;
                if (mesh != null)
                {
                    for (int subMeshIndex = 0; subMeshIndex < mesh.subMeshCount; subMeshIndex++)
                        totalTriangles += (int)(mesh.GetIndexCount(subMeshIndex) / 3);
                }
                RepairMesh(mesh);
            }

            if (totalTriangles > AutoLodTriangleThreshold && importedRoot.GetComponentInChildren<LODGroup>(true) == null)
            {
                bool hasForgeContract = TryResolveForgeImportContract(assetPath, out ForgeImportContract forgeContract);
                if (hasForgeContract && forgeContract.AuthoredLodLevelCount > 1)
                {
                    // The package already authored its own chain, so decimating LOD0 into __AUTO_LOD1/
                    // __AUTO_LOD2 would ship five LODs where the manifest declares three, and would decimate
                    // the COL_ collision proxy along with them. 3dmodel.md section 7 owns the chain; the
                    // Unity-side authoring pass owns binding it to an LODGroup, which no importer can do from
                    // the FBX alone. LogError, not throw: the asset must still import so that pass can run.
                    Debug.LogError(
                        "[HectonFBXPostprocessor] Forge package '" + assetPath + "' declares " +
                        forgeContract.AuthoredLodLevelCount + " authored LOD levels in manifest '" +
                        forgeContract.ManifestPath + "' but imported without an LODGroup (Tris: " +
                        totalTriangles + "). The auto-decimation fallback is SUPPRESSED so the authored chain " +
                        "is not duplicated. Bind the _LOD<n> children to an LODGroup with fadeMode=CrossFade " +
                        "and animateCrossFading=false through the Unity-side authoring pass, per 3dmodel.md " +
                        "section 7.");
                }
                else if (TryCreateFallbackLodGroup(importedRoot))
                {
                    Debug.LogWarning($"[HectonFBXPostprocessor] Auto-generated LOD1/LOD2 fallback for high-poly model: {assetPath} (Tris: {totalTriangles}).");
                }
                else
                {
                    Debug.LogWarning($"[CRITICAL WARNING] High-poly mesh (>{AutoLodTriangleThreshold} tris) without LOD Group and no valid renderers for fallback authoring: {assetPath} (Tris: {totalTriangles})");
                }
            }

            SkinnedMeshRenderer[] skinnedRenderers = importedRoot.GetComponentsInChildren<SkinnedMeshRenderer>(true);
            for (int i = 0; i < skinnedRenderers.Length; i++)
                RepairMesh(skinnedRenderers[i] != null ? skinnedRenderers[i].sharedMesh : null);

            if (HectonBakeryUvAudit.TryValidateImportedModelUv2(importedRoot, assetPath, out string uvFailure))
            {
                throw new InvalidOperationException("[HectonFBXPostprocessor] " + uvFailure);
            }
        }

        private static bool TryCreateFallbackLodGroup(GameObject importedRoot)
        {
            if (importedRoot == null)
                return false;

            MeshFilter[] meshFilters = importedRoot.GetComponentsInChildren<MeshFilter>(true);
            List<Renderer> lod0Renderers = new List<Renderer>(meshFilters.Length);
            List<Renderer> lod1Renderers = new List<Renderer>(meshFilters.Length);
            List<Renderer> lod2Renderers = new List<Renderer>(meshFilters.Length);

            for (int i = 0; i < meshFilters.Length; i++)
            {
                MeshFilter sourceFilter = meshFilters[i];
                if (sourceFilter == null || sourceFilter.sharedMesh == null)
                    continue;

                MeshRenderer sourceRenderer = sourceFilter.GetComponent<MeshRenderer>();
                if (sourceRenderer == null || !sourceRenderer.enabled)
                    continue;

                lod0Renderers.Add(sourceRenderer);
                Mesh lod1Mesh = HectonEditorMeshUtility.BuildDecimatedMesh(
                    sourceFilter.sharedMesh,
                    AutoGeneratedLod1TriangleRatio,
                    0,
                    sourceFilter.sharedMesh.name + "_AUTO_LOD1");
                Mesh lod2Mesh = HectonEditorMeshUtility.BuildDecimatedMesh(
                    sourceFilter.sharedMesh,
                    AutoGeneratedLod2TriangleRatio,
                    0,
                    sourceFilter.sharedMesh.name + "_AUTO_LOD2");

                if (lod1Mesh != null)
                    lod1Renderers.Add(CreateLodRenderer(sourceFilter, sourceRenderer, lod1Mesh, "__AUTO_LOD1"));
                if (lod2Mesh != null)
                    lod2Renderers.Add(CreateLodRenderer(sourceFilter, sourceRenderer, lod2Mesh, "__AUTO_LOD2"));
            }

            if (lod0Renderers.Count <= 0 || lod1Renderers.Count <= 0 || lod2Renderers.Count <= 0)
                return false;

            LODGroup lodGroup = importedRoot.GetComponent<LODGroup>();
            if (lodGroup == null)
                lodGroup = importedRoot.AddComponent<LODGroup>();

            LOD[] lods =
            {
                new LOD(AutoGeneratedLod0ScreenRelativeHeight, lod0Renderers.ToArray())
                {
                    fadeTransitionWidth = AutoGeneratedLodFadeWidth
                },
                new LOD(AutoGeneratedLod1ScreenRelativeHeight, lod1Renderers.ToArray())
                {
                    fadeTransitionWidth = AutoGeneratedLodFadeWidth
                },
                new LOD(AutoGeneratedLod2ScreenRelativeHeight, lod2Renderers.ToArray())
                {
                    fadeTransitionWidth = AutoGeneratedLodFadeWidth
                }
            };
            lodGroup.fadeMode = LODFadeMode.CrossFade;
            lodGroup.animateCrossFading = false;
            lodGroup.SetLODs(lods);
            lodGroup.RecalculateBounds();
            EditorUtility.SetDirty(importedRoot);
            return true;
        }

        private static MeshRenderer CreateLodRenderer(
            MeshFilter sourceFilter,
            MeshRenderer sourceRenderer,
            Mesh mesh,
            string suffix)
        {
            GameObject lodObject = new GameObject(sourceFilter.gameObject.name + suffix);
            Transform sourceTransform = sourceFilter.transform;
            Transform lodTransform = lodObject.transform;
            if (sourceTransform.parent != null)
            {
                lodTransform.SetParent(sourceTransform.parent, false);
                lodTransform.localPosition = sourceTransform.localPosition;
                lodTransform.localRotation = sourceTransform.localRotation;
                lodTransform.localScale = sourceTransform.localScale;
            }
            else
            {
                lodTransform.SetParent(sourceTransform, false);
                lodTransform.localPosition = Vector3.zero;
                lodTransform.localRotation = Quaternion.identity;
                lodTransform.localScale = Vector3.one;
            }

            MeshFilter lodFilter = lodObject.AddComponent<MeshFilter>();
            lodFilter.sharedMesh = mesh;

            MeshRenderer lodRenderer = lodObject.AddComponent<MeshRenderer>();
            lodRenderer.sharedMaterials = sourceRenderer.sharedMaterials;
            lodRenderer.lightProbeUsage = sourceRenderer.lightProbeUsage;
            lodRenderer.reflectionProbeUsage = sourceRenderer.reflectionProbeUsage;
            lodRenderer.shadowCastingMode = sourceRenderer.shadowCastingMode;
            lodRenderer.receiveShadows = sourceRenderer.receiveShadows;
            lodRenderer.motionVectorGenerationMode = sourceRenderer.motionVectorGenerationMode;
            return lodRenderer;
        }

        internal static bool ApplyImporterPolicy(ModelImporter importer)
        {
            if (importer == null)
                return false;

            bool changed = false;
            bool isScifiFacilityModel = IsUnderRoot(importer.assetPath, ScifiFacilityRoot);
            bool hasForgeContract = TryResolveForgeImportContract(importer.assetPath, out ForgeImportContract forgeContract);
            if (importer.materialLocation != ModelImporterMaterialLocation.InPrefab)
            {
                importer.materialLocation = ModelImporterMaterialLocation.InPrefab;
                changed = true;
            }

            // The forge ships shared MAT_* assets and strips every texture path out of the FBX
            // (Tools/Blender/generators/kelp.py path_mode="STRIP"; manifest materialSlots names
            // MAT_Flora_tissue and siblings), so letting Unity build materials from the file would create
            // per-model materials and break the shared-material rule in 3dmodel.md section 8. materialLocation
            // above is deliberately left exactly as the project policy sets it: with materialImportMode None
            // there are no imported materials for it to place, so ImporterMatchesScifiFacilityPolicy keeps
            // asserting InPrefab and stays true by construction.
            if (hasForgeContract &&
                forgeContract.SuppressMaterialImport &&
                importer.materialImportMode != ModelImporterMaterialImportMode.None)
            {
                importer.materialImportMode = ModelImporterMaterialImportMode.None;
                changed = true;
            }

            // isReadable was forced false UNCONDITIONALLY here, with no comment stating why. A readable mesh
            // keeps a CPU-side copy resident, so false is the right default across 2740+ FBX and that default
            // is preserved exactly: for every asset that is not a declared VAT source this evaluates to
            // `if (importer.isReadable) importer.isReadable = false;`, which is what the line did before.
            //
            // The carve-out exists because a VAT source is the one case where the CPU copy is the POINT.
            // FaunaHeadlessBake1610 reads Mesh.vertices to build the position/normal pages, and a mesh whose
            // vertex array reads back empty would produce a full-size VAT page of zeros that looks like a
            // successful bake on disk (AbyssalAnatomyStudio1610.VerifyMeshIsReadable refuses exactly that).
            //
            // FAIL CLOSED: `hasForgeContract` is false when no sibling manifest exists, when it cannot be
            // parsed, or when it is under ScifiFacilityRoot (TryResolveForgeManifestPath:715). IsVatSource is
            // granted only by a tier-1 `h8forge.manifest/1` manifest carrying a vatReadiness block with a
            // positive vertexCountLOD0. Any doubt anywhere in that chain lands on today's behaviour.
            //
            // ImporterMatchesScifiFacilityPolicy asserts !isReadable, but that assertion is scoped to
            // ScifiFacilityRoot (:559-561) and the forge carve-out can never apply under that root, so the two
            // sets are disjoint by construction and the vendor policy cannot be weakened from here.
            bool vatSourceNeedsReadableGeometry = hasForgeContract && forgeContract.IsVatSource;
            if (importer.isReadable != vatSourceNeedsReadableGeometry)
            {
                importer.isReadable = vatSourceNeedsReadableGeometry;
                changed = true;
            }

            if (importer.importBlendShapes)
            {
                importer.importBlendShapes = false;
                changed = true;
            }

            if (importer.importVisibility)
            {
                importer.importVisibility = false;
                changed = true;
            }

            if (importer.importCameras)
            {
                importer.importCameras = false;
                changed = true;
            }

            if (isScifiFacilityModel)
            {
                if (importer.importNormals != ModelImporterNormals.Calculate)
                {
                    importer.importNormals = ModelImporterNormals.Calculate;
                    changed = true;
                }
                if (!Mathf.Approximately(importer.normalSmoothingAngle, ScifiFacilityNormalSmoothingAngle))
                {
                    importer.normalSmoothingAngle = ScifiFacilityNormalSmoothingAngle;
                    changed = true;
                }
                if (importer.importTangents != ModelImporterTangents.CalculateMikk)
                {
                    importer.importTangents = ModelImporterTangents.CalculateMikk;
                    changed = true;
                }
                if (!importer.weldVertices)
                {
                    importer.weldVertices = true;
                    changed = true;
                }
            }
            else if (hasForgeContract && forgeContract.ImportAuthoredNormals)
            {
                // THE conflict this carve-out exists for. mesh_ops.apply_shading_basis bakes 3dmodel.md
                // section 4's weightedNormal(v, group) formula into custom split normals and the generator
                // applies the modifier before export, so the FBX carries an authored basis. Section 3:
                // "RecalculateNormals, RecalculateTangents, and RecalculateBounds are allowed only as editor
                // fallback after a documented failure, never as the default strategy. A generator owns
                // normals, tangents, UVs, and bounds because it owns the geometry." Calculate re-derives them
                // from a single angle and throws every bevel-shading decision away.
                if (importer.importNormals != ModelImporterNormals.Import)
                {
                    importer.importNormals = ModelImporterNormals.Import;
                    changed = true;
                }

                // Inert while importNormals is Import. It is still written when the manifest declares one, so
                // that a forced fallback to Calculate reproduces the authored split from the same dihedral
                // angle the generator used instead of an unrelated one.
                if (forgeContract.NormalSmoothingAngle > ForgeMinNormalSmoothingAngle &&
                    !Mathf.Approximately(importer.normalSmoothingAngle, forgeContract.NormalSmoothingAngle))
                {
                    importer.normalSmoothingAngle = forgeContract.NormalSmoothingAngle;
                    changed = true;
                }

                // Unchanged from the project default on purpose: the forge's own import contract asks for
                // CalculateMikk too, because under MikkTSpace the tangent is fully determined by position,
                // normal and UV0, and no Blender-side round trip can prove the handedness w survives Unity's
                // left-handed flip. This is not one of the conflicts.
                if (importer.importTangents != ModelImporterTangents.CalculateMikk)
                {
                    importer.importTangents = ModelImporterTangents.CalculateMikk;
                    changed = true;
                }
            }
            else
            {
                if (importer.importNormals != ModelImporterNormals.Calculate)
                {
                    importer.importNormals = ModelImporterNormals.Calculate;
                    changed = true;
                }
                if (importer.importTangents != ModelImporterTangents.CalculateMikk)
                {
                    importer.importTangents = ModelImporterTangents.CalculateMikk;
                    changed = true;
                }
            }

            // Unity's secondary-UV generator OVERWRITES UV1, and 3dmodel.md section 3 makes TexCoord1
            // authored data: "Lightmap, detail, atlas remap, or packed baked masks when required." Forcing it
            // back off here also repairs a package that an earlier HectonBakeryUvAudit pass flipped on, because
            // the FBX still carries the authored channel and the next import reads it again. Only a manifest
            // that explicitly declares generateSecondaryUV=false reaches this branch.
            if (hasForgeContract && forgeContract.SuppressSecondaryUv && importer.generateSecondaryUV)
            {
                importer.generateSecondaryUV = false;
                changed = true;
            }

            if (importer.generateSecondaryUV)
            {
                if (!Mathf.Approximately(importer.secondaryUVHardAngle, DeterministicSecondaryUvHardAngle))
                {
                    importer.secondaryUVHardAngle = DeterministicSecondaryUvHardAngle;
                    changed = true;
                }

                if (!Mathf.Approximately(importer.secondaryUVAngleDistortion, DeterministicSecondaryUvAngleDistortion))
                {
                    importer.secondaryUVAngleDistortion = DeterministicSecondaryUvAngleDistortion;
                    changed = true;
                }

                if (!Mathf.Approximately(importer.secondaryUVAreaDistortion, DeterministicSecondaryUvAreaDistortion))
                {
                    importer.secondaryUVAreaDistortion = DeterministicSecondaryUvAreaDistortion;
                    changed = true;
                }

                if (importer.secondaryUVPackMargin != DeterministicSecondaryUvPackMargin)
                {
                    importer.secondaryUVPackMargin = DeterministicSecondaryUvPackMargin;
                    changed = true;
                }
            }

            // Scoped to the vendor tree ON PURPOSE, and left that way after review. Position quantisation on a
            // VAT source would perturb the very positions the bake samples, but forge assets never reach this
            // line: the guard is isScifiFacilityModel, and MESH_Fauna_Fish_2207_00.fbx.meta:41 carries
            // meshCompression: 0 (Off) on disk, matching its own manifest's declared "meshCompression": "Off".
            // A report that Medium is applied to forge assets is incorrect - there is nothing to carve out.
            if (isScifiFacilityModel && importer.meshCompression != ModelImporterMeshCompression.Medium)
            {
                importer.meshCompression = ModelImporterMeshCompression.Medium;
                changed = true;
            }

            // VAT DURABILITY CONTRACT. Both fields below are declared by every h8forge manifest and, until
            // now, applied by nothing - the manifest's own note says "the importer block disables vertex
            // optimisation and welding", while Unity's defaults (weldVertices true, meshOptimizationFlags
            // Everything) did the opposite. A declared parameter that nothing enforces is the same defect
            // class as a gate that cannot fire.
            //
            // Both change per-vertex IDENTITY, and a baked VAT is indexed by vertexID
            // (BoidFishInstanced.shader:493), so applying either AFTER a VAT exists desynchronises the texture
            // from the mesh and the swarm animates as noise while every null check passes. That is why this is
            // safe to land now and expensive to land later: no VAT has ever been baked in this project.
            //
            // Deliberately NOT inside the isScifiFacilityModel branch above: that root can never hold a forge
            // contract, and ImporterMatchesScifiFacilityPolicy requires weldVertices TRUE for it (:571). The
            // two policies are opposites and must stay on disjoint asset sets.
            if (hasForgeContract && forgeContract.IsVatSource)
            {
                if (importer.weldVertices)
                {
                    importer.weldVertices = false;
                    changed = true;
                }

                // PolygonOrder reorders triangles only, which touches no per-vertex identity. The default
                // Everything additionally reorders VERTICES, which is the one thing a VAT cannot survive.
                if (importer.meshOptimizationFlags != MeshOptimizationFlags.PolygonOrder)
                {
                    importer.meshOptimizationFlags = MeshOptimizationFlags.PolygonOrder;
                    changed = true;
                }
            }

            if (hasForgeContract)
                LogForgeCarveOut(importer.assetPath, forgeContract);

            return changed;
        }

        private void NormalizeImportedRootName(GameObject importedRoot)
        {
            if (importedRoot == null || !IsUnderRoot(assetPath, ScifiFacilityRoot))
                return;

            string assetName = System.IO.Path.GetFileNameWithoutExtension(assetPath);
            if (string.IsNullOrEmpty(assetName) ||
                string.Equals(importedRoot.name, assetName, StringComparison.Ordinal))
            {
                return;
            }

            importedRoot.name = assetName;
            EditorUtility.SetDirty(importedRoot);
        }

        private static void RepairMesh(Mesh mesh)
        {
            if (mesh == null)
                return;

            int vertexCount = mesh.vertexCount;
            if (vertexCount <= 0)
            {
                mesh.SetNormals(EmptyVertices);
                mesh.SetTangents(EmptyTangents);
                EditorUtility.SetDirty(mesh);
                return;
            }

            bool missingNormals = !mesh.HasVertexAttribute(UnityEngine.Rendering.VertexAttribute.Normal);
            if (missingNormals)
                mesh.RecalculateNormals();

            bool missingTangents = !mesh.HasVertexAttribute(UnityEngine.Rendering.VertexAttribute.Tangent);
            bool hasUv0 = mesh.HasVertexAttribute(UnityEngine.Rendering.VertexAttribute.TexCoord0);
            if (missingTangents && hasUv0)
                mesh.RecalculateTangents();

            if (missingNormals || (missingTangents && hasUv0))
                EditorUtility.SetDirty(mesh);
        }

        private static bool IsManagedModelAsset(string path)
        {
            if (string.IsNullOrEmpty(path))
                return false;

            string normalizedPath = path.Replace('\\', '/');
            for (int i = 0; i < ManagedFbxRoots.Length; i++)
            {
                if (IsUnderRoot(normalizedPath, ManagedFbxRoots[i]))
                    return true;
            }

            return false;
        }

        private static bool ImporterMatchesScifiFacilityPolicy(ModelImporter importer)
        {
            if (importer == null || !IsUnderRoot(importer.assetPath, ScifiFacilityRoot))
                return false;

            return !importer.isReadable &&
                   !importer.importBlendShapes &&
                   !importer.importVisibility &&
                   !importer.importCameras &&
                   importer.materialLocation == ModelImporterMaterialLocation.InPrefab &&
                   importer.importNormals == ModelImporterNormals.Calculate &&
                   Mathf.Approximately(importer.normalSmoothingAngle, ScifiFacilityNormalSmoothingAngle) &&
                   importer.importTangents == ModelImporterTangents.CalculateMikk &&
                   importer.weldVertices &&
                   importer.meshCompression == ModelImporterMeshCompression.Medium;
        }

        /// <summary>
        /// Editor-only carve-out record for one offline Blender forge package. This is not a runtime DTO and it
        /// crosses no native/Burst/persistence/GPU boundary, so managed fields are allowed on it.
        /// </summary>
        internal readonly struct ForgeImportContract
        {
            /// <summary>Project-relative path of the manifest that authorised the carve-out.</summary>
            internal readonly string ManifestPath;
            /// <summary>
            /// True when the manifest carried an explicit <c>unityImport.modelImporter</c> block
            /// (<c>h8forge.manifest/1</c> from <c>h8forge.export_unity.write_manifest</c>). False when
            /// provenance was established from the generator-local manifest shape instead, in which case every
            /// relaxation is derived from a field that manifest genuinely carries and nothing is assumed.
            /// </summary>
            internal readonly bool DeclaredImportContract;
            internal readonly bool ImportAuthoredNormals;
            /// <summary>Authored dihedral smoothing angle, or 0 when the manifest declared none.</summary>
            internal readonly float NormalSmoothingAngle;
            internal readonly bool SuppressSecondaryUv;
            internal readonly bool SuppressMaterialImport;
            internal readonly int AuthoredLodLevelCount;
            /// <summary>
            /// True only when a tier-1 manifest declares a <c>vatReadiness</c> block with a positive
            /// <c>vertexCountLOD0</c>. Gates BOTH the isReadable carve-out and the vertex-identity settings,
            /// because those are the two things a Vertex Animation Texture source needs and nothing else does.
            /// Tier 2 always passes false: a generator-local manifest declares no importer contract at all, so
            /// granting a relaxation from it would be an assumption rather than a reading.
            /// </summary>
            internal readonly bool IsVatSource;

            internal ForgeImportContract(
                string manifestPath,
                bool declaredImportContract,
                bool importAuthoredNormals,
                float normalSmoothingAngle,
                bool suppressSecondaryUv,
                bool suppressMaterialImport,
                int authoredLodLevelCount,
                bool isVatSource)
            {
                ManifestPath = manifestPath;
                DeclaredImportContract = declaredImportContract;
                ImportAuthoredNormals = importAuthoredNormals;
                NormalSmoothingAngle = normalSmoothingAngle;
                SuppressSecondaryUv = suppressSecondaryUv;
                SuppressMaterialImport = suppressMaterialImport;
                AuthoredLodLevelCount = authoredLodLevelCount;
                IsVatSource = isVatSource;
            }
        }

