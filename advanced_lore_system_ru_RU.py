def generate_sentence(category):
    if category == "marauder":
        return f"{random.choice(nouns_marauder)} {random.choice(verbs_marauder)} {random.choice(details_marauder)}"
    elif category == "corp":
        return f"{random.choice(nouns_corp)} {random.choice(verbs_corp)} {random.choice(details_corp)}"
    elif category == "scanner":
        return f"{random.choice(nouns_scanner)} {random.choice(verbs_scanner)}. {random.choice(details_scanner)}"
    elif category == "audio":
        return f"{random.choice(details_audio)} {random.choice(nouns_audio)} {random.choice(verbs_audio)}."
    elif category == "blackbox":
        return f"{random.choice(nouns_blackbox)} {random.choice(verbs_blackbox)}. {random.choice(details_blackbox)}"
    elif category == "wiki":
        return f"{random.choice(nouns_wiki)} {random.choice(verbs_wiki)}. {random.choice(details_wiki)}"
    elif category == "codex":
        return f"{random.choice(nouns_codex)} {random.choice(verbs_codex)}. {random.choice(details_codex)}"
    else:
        return "Системная ошибка."

def generate_paragraph(category, min_sentences=3, max_sentences=6):
    num_sentences = random.randint(min_sentences, max_sentences)
    sentences = [generate_sentence(category) for _ in range(num_sentences)]
    return " ".join(sentences)

def expand_to_word_count(text, target_words):
    words = text.split()
    while len(words) < target_words:
        cat = random.choice(["marauder", "corp", "scanner", "audio", "blackbox", "wiki", "codex"])
        text += " " + generate_sentence(cat)
        words = text.split()
    return text

